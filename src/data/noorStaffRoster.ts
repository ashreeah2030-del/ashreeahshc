/**
 * Convert NoorOfficialRecord list into StaffMember list
 */
export function convertNoorRecordsToStaff(
  records: NoorOfficialRecord[] = NOOR_OFFICIAL_STAFF_ROSTER
): Omit<StaffMember, 'id'>[] {
  return records.map((rec) => ({
    nationalId: rec.nationalId,
    name: rec.name,
    phone: rec.phone,
    role: rec.role,
    roleTitle: rec.roleTitle,
    stage: rec.stage,
    subject: rec.subject,
    notes: `مستورد من نظام نور (${rec.rank}) - تخصص: ${rec.noorSpecialty}`,
    active: true,
    pin: rec.nationalId.slice(-4),
  }));
}

/**
 * Search/Lookup in official Noor records by National ID or Name
 */
export function lookupNoorRecord(query: string): NoorOfficialRecord | undefined {
  const cleanQ = query.trim().replace(/[^0-9]/g, '');
  if (cleanQ.length >= 4) {
    const byId = NOOR_OFFICIAL_STAFF_ROSTER.find((r) => r.nationalId.includes(cleanQ));
    if (byId) return byId;
  }
  const byName = NOOR_OFFICIAL_STAFF_ROSTER.find((r) => r.name.includes(query.trim()));
  return byName;
}
